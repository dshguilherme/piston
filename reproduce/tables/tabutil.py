"""Shared helpers for the table drivers: CSV reading, parsing a typed table out of the manuscript,
and comparing computed values with the printed ones at the printed precision.

The manuscript (paper_jsv/prototype/manuscript_proto_voice.tex) is read only. If it is absent (for
example in a public copy without the paper source), the drivers still write their tables and report
the comparison as SKIP.
"""
import csv
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir))
import config as C  # noqa: E402

MANUSCRIPT = os.path.join(C.PAPER, "prototype", "manuscript_proto_voice.tex")
NUM = re.compile(r"[-+]?\d+(?:\.\d+)?")


def rd(path):
    with open(path, newline="") as f:
        return [r for r in csv.DictReader(f) if not str(list(r.values())[0]).startswith("#")]


def manuscript_table(label):
    """Rows of the tabular that follows \\label{<label>}, as lists of raw cell strings, or None."""
    if not os.path.exists(MANUSCRIPT):
        return None
    with open(MANUSCRIPT, encoding="utf-8") as f:
        lines = f.read().splitlines()
    start = next(i for i, ln in enumerate(lines) if "\\label{%s}" % label in ln)
    rows, inside = [], False
    for ln in lines[start:]:
        s = ln.strip()
        if s.startswith("\\bottomrule"):
            break
        if s.startswith("\\midrule"):
            inside = True
            continue
        if inside and "&" in s:
            rows.append([c.strip() for c in s.rstrip("\\").split("&")])
    return rows


def manuscript_line(pattern, after_label=None):
    """First manuscript line matching a regex (optionally searched after a label), or None."""
    if not os.path.exists(MANUSCRIPT):
        return None
    with open(MANUSCRIPT, encoding="utf-8") as f:
        lines = f.read().splitlines()
    i0 = 0
    if after_label:
        i0 = next(i for i, ln in enumerate(lines) if "\\label{%s}" % after_label in ln)
    rx = re.compile(pattern)
    return next((ln for ln in lines[i0:] if rx.search(ln)), None)


def cell_number(cell):
    """Numeric value of a typed cell: strips TeX ($, ^\\circ, \\rlap{...}); None for '---' or text."""
    s = re.sub(r"\\rlap\{.*?\}\}?", "", cell)
    s = s.replace("$", "").replace("^\\circ", "").replace("\\,", "")
    m = NUM.search(s)
    return float(m.group()) if m and not s.strip().startswith("---") else None


def decimals(cell):
    s = re.sub(r"\\rlap\{.*?\}\}?", "", cell).replace("$", "")
    m = NUM.search(s)
    if not m or "." not in m.group():
        return 0
    return len(m.group().split(".")[1])


def agrees(value, cell):
    """True if value rounds to the printed number (half a unit of the last printed digit)."""
    printed = cell_number(cell)
    if printed is None:
        return value is None
    return abs(value - printed) <= 0.5 * 10 ** (-decimals(cell)) + 1e-9


def report(name, computed, typed, numeric_cols):
    """Compare computed rows (lists of floats/None, aligned with typed rows) with typed rows.
    numeric_cols: indices of typed cells to compare. Returns (n_checked, list of mismatches)."""
    if typed is None:
        print("%s: manuscript not found, comparison SKIP" % name)
        return 0, []
    bad, n = [], 0
    for r, (crow, trow) in enumerate(zip(computed, typed)):
        for j, col in enumerate(numeric_cols):
            n += 1
            if not agrees(crow[j], trow[col]):
                bad.append((r, col, crow[j], trow[col]))
    if len(computed) != len(typed):
        bad.append(("rows", len(computed), len(typed), "row count differs"))
    print("%s: %d typed cells compared, %d mismatches" % (name, n, len(bad)))
    for b in bad:
        print("  MISMATCH row %s col %s: computed %s, typed %s" % b)
    return n, bad


def write_table(stem, header, rows, fmt):
    """Write <REPRO_OUT>/tables/<stem>.csv (full precision) and <stem>.tex (rows at printed precision)."""
    d = C.out("tables")
    with open(os.path.join(d, stem + ".csv"), "w", newline="\n") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)
    with open(os.path.join(d, stem + ".tex"), "w", newline="\n") as f:
        f.write("%% generated by reproduce/tables/%s.py from stored results; do not edit\n" % stem.replace("tab_", "make_tab_"))
        for r in rows:
            f.write(" & ".join(fmt[j](v) for j, v in enumerate(r)) + " \\\\\n")
    print("wrote", os.path.join(d, stem + ".csv"), "and .tex")


def f(dec, sign=False):
    def g(v):
        if v is None:
            return "---"
        s = ("%+." if sign else "%.") + str(dec) + "f"
        return s % v
    return g
